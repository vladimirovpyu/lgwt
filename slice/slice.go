package main

import "fmt"

// Функция получает копию структуры слайса (ptr, len, cap).
// Сначала добавляет элемент, потом меняет первый элемент.
func modify(s []int) {
  // Если в массиве есть свободное место (len < cap), append пишет
  // в ТОТ ЖЕ массив, и s продолжает смотреть на общие данные.
  // Если места нет (len == cap), append создает НОВЫЙ массив большего размера,
  // копирует туда данные, и s теперь смотрит на новый массив.
  s = append(s, 100)

  // Попадет ли эта запись к вызывающему, решила строка выше:
  // массив общий - попадет, массив новый - потеряется.
  s[0] = 999
}

func main() {
  var s []int // пустой слайс: len=0, cap=0

  for i := 1; i <= 5; i++ {
    // Добавляем элемент. Когда места не хватает, Go сам выделяет
    // массив побольше (для маленьких слайсов обычно в 2 раза больше).
    s = append(s, i)

    s[0] = 0 // сбрасываем, чтобы было видно, поменяла ли его функция

    // Запоминаем len и cap ДО вызова: от них зависит результат
    l, c := len(s), cap(s)

    modify(s)

    if s[0] == 999 {
      fmt.Printf("len=%d cap=%d -> изменение ДОШЛО (было место, массив общий)\n", l, c)
    } else {
      fmt.Printf("len=%d cap=%d -> изменение ПОТЕРЯЛОСЬ (места нет, append сделал новый массив)\n", l, c)
    }
  }
}
