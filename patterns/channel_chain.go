/**

### Паттерн: Ordered Fan-In / Эстафетная цепочка каналов (Pipeline Synchronization)

Позволяет выполнять тяжёлые задачи **конкурентно и в случайном порядке**, но записывать их результаты в общий канал **строго в исходной последовательности** (0, 1, 2, 3, 4).

#### Как это работает
1. **Цепочка сигнальных каналов.** Каждая горутина получает два служебных канала: `waitFor` (сигнал от предыдущей) и `signalNext` (сигнал для следующей).
2. **Параллельное выполнение работы.** Сама полезная нагрузка (`time.Sleep` и формирование `result`) выполняется всеми горутинами одновременно, без блокировок и ожидания друг друга.
3. **Синхронизация только на этапе записи.** Сделав свою работу, быстрая горутина упирается в `<-waitFor` и ждёт, пока предыдущая не завершит отправку своего результата.
4. **Передача эстафеты.** Как только горутина отправила данные в `out`, она вызывает `close(signalNext)`, тем самым разблокируя следующую по очереди горутину. Для самой первой горутины (`i = 0`) стартовый канал закрывается заранее.

#### Ключевые нюансы реализации
* **Почему `close(signalNext)`, а не отправка значения?** Закрытие канала не требует наличия активного получателя в ту же миллисекунду. Если следующая горутина ещё не закончила свои вычисления и не дошла до `<-waitFor`, закрытие не заблокирует текущую горутину — следующая просто прочитает «закрыто» без задержки, когда подойдёт её очередь.
* **Риск эффекта «головы очереди» (Head-of-Line Blocking).** Если горутина №1 зависнет надолго, горутины №2, №3 и №4 уже выполнят свою работу, но будут простаивать в памяти в ожидании своей очереди на запись в `out`.
* **Отсутствие `WaitGroup` и закрытия `out`.** В примере читатель заранее знает точное количество сообщений (`cnt = 5`), поэтому читает ровно `cnt` раз и не закрывает канал `out`. В реальном коде после цикла обычно добавляют `close(out)` (либо через `<-prevTurn` после цикла, так как последний `prevTurn` — это `signalNext` самой последней горутины).
* **Обязательная передача переменных в горутину.** Аргументы `i, prevTurn, nextTurn` передаются как параметры анонимной функции, чтобы избежать захвата меняющихся переменных цикла по ссылке.
* **Отсутствие отмены (Cancel).** Если одна из горутин в середине цепочки упадёт (panic) до вызова `close(signalNext)`, вся оставшаяся часть цепочки зависнет навсегда (deadlock).

*/

package main

import (
	"fmt"
	"math/rand"
	"time"
)

func main() {
	out := make(chan string) // Общий выходной канал для результатов
	cnt := 5

	// Начальный сигнальный канал для первой горутины (i = 0)
	prevTurn := make(chan struct{})
	close(prevTurn) // Закрываем сразу, чтобы горутина 0 могла писать без ожидания

	for i := 0; i < cnt; i++ {
		nextTurn := make(chan struct{}) // Сигнальный канал для следующей горутины

		go func(id int, waitFor, signalNext chan struct{}) {
			// 1. Полезная работа выполняется конкурентно и с разной скоростью
			time.Sleep(time.Duration(rand.Intn(100)) * time.Millisecond)
			result := fmt.Sprintf("Goroutine %d", id)

			// 2. Ждём своей очереди (пока предыдущая горутина не закроет канал)
			<-waitFor

			// 3. Пишем в общий канал строго по порядку
			out <- result

			// 4. Передаём эстафету следующей горутине
			close(signalNext)
		}(i, prevTurn, nextTurn)

		// Сдвигаем указатель для следующей итерации цикла
		prevTurn = nextTurn
	}

	// Читаем из общего канала — порядок гарантирован (0, 1, 2, 3, 4)
	for i := 0; i < cnt; i++ {
		fmt.Println(<-out)
	}
}
