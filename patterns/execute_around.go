/*
У этого приёма есть несколько устоявшихся названий в Go-сообществе и программировании в целом.

Основные названия в Go и архитектуре

• Execute Around (Выполнение вокруг) — классический паттерн объектно-ориентированного и функционального программирования. Его суть в том, что метод берёт на себя подготовку и освобождение ресурса (захват и снятие мьютекса, открытие и закрытие файла/транзакции), а полезную работу принимает в виде коллбэка и выполняет её «внутри» этой обёртки.
• WithLock / WithRLock (Функциональная обёртка над мьютексом) — идиоматичное название конкретно для языка Go. В кодовых базах такие хелперы почти всегда называют с префиксом With... (например, withLock, withTx, withConn).
• Scoped Locking (Блокировка в области видимости) — паттерн из книги Дугласа Шмидта (POSA2), привязывающий время жизни блокировки к времени жизни локальной области видимости (в C++ это реализуется через деструкторы и RAII, а в Go — через замыкание функции и defer).

Зачем его используют в Go

• Изоляция области действия defer: В Go defer привязан не к блоку кода ({ ... }), а ко всей функции целиком. Вынос критической секции в отдельную функцию-обёртку искусственно создаёт узкую область видимости для defer.
• Защита от забытого Unlock(): Даже если внутри коллбэка произойдёт паника или ранний выход, defer гарантированно освободит мьютекс.
*/

// Вспомогательные обёртки для работы с мьютексом
func (c *Cache) withRLock(fn func()) {
	c.mu.RLock()
	defer c.mu.RUnlock() // Гарантированно снимет RLock при выходе из fn
	fn()
}

func (c *Cache) withLock(fn func()) {
	c.mu.Lock()
	defer c.mu.Unlock() // Гарантированно снимет Lock при выходе из fn
	fn()
}

// Использование в методе Get без риска deadlock:
func (c *Cache) Get(key string) (string, error) {
	var val string
	var ok bool

	// 1. Читаем под RLock; блокировка снимается сразу после выхода из коллбэка
	c.withRLock(func() {
		val, ok = c.data[key]
	})
	if ok {
		return val, nil
	}

	// 2. Идём в БД вообще без блокировок (не тормозим другие горутины)
	val, err := c.db.Get(key)
	if err != nil {
		return "", err
	}

	// 3. Пишем результат под обычным Lock; блокировка также снимается через defer
	c.withLock(func() {
		c.data[key] = val
	})

	return val, nil
}
