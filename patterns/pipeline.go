/**
### Паттерн: Конвейер (Pipeline)

Разбивает обработку данных на последовательность независимых этапов (стадий), соединённых каналами. Каждая стадия принимает входной канал, обрабатывает элементы на лету в отдельной горутине и возвращает новый выходной канал.

#### Как это работает
1. **Генератор (`writer`).** Источник данных. Создаёт канал, запускает горутину для генерации значений, сразу возвращает канал наружу и закрывает его по завершении (`defer close(out)`).
2. **Трансформер (`doubler`).** Промежуточный этап. Читает данные из входного канала (`in`), применяет логику (умножает на 2) и пишет в свой выходной канал (`out`). Как только `in` закрывается, цикл `range` завершается, и `doubler` закрывает свой `out`.
3. **Потребитель (`reader`).** Финальная стадия. Работает в основной горутине `main`, вычитывая готовые результаты до тех пор, пока предыдущий этап не закроет канал.

#### Ключевые нюансы реализации
* **Владение каналом и `defer close(out)`.** Главное правило Go соблюдено идеально: канал закрывает только та горутина, которая в него пишет. Использование `defer` гарантирует закрытие канала при любом выходе из функции, что запускает каскадное завершение всего конвейера.
* **Направление каналов (`<-chan int`).** Все функции возвращают и принимают каналы только для чтения. Это запрещает следующим этапам случайно записать данные назад или закрыть чужой канал.
* **Естественное противодавление (Backpressure).** Каналы небуферизованные, а в `doubler` стоит задержка 500 мс. Из-за этого `writer` не генерирует все 10 чисел мгновенно, а ждёт, пока `doubler` заберёт текущее число и передаст его в `reader`. Память не переполняется.
* **Синхронный финиш в `main`.** Поскольку `reader` запущен без `go` (в главной горутине), программа сама ждёт обработки всех 10 элементов, и здесь не нужен `sync.WaitGroup`.
* **Уязвимость к досрочному выходу (Leak).** Как и в базовом Fan-In, здесь нет `context.Context` или канала `done`. Если `reader` решит остановиться после 3-го элемента (`break`), горутины `writer` и `doubler` останутся заблокированными в памяти навсегда на попытке записи в канал.

*/

package main

import (
	"fmt"
	"time"
)

func writer() <-chan int {
	out := make(chan int)

	go func() {
		defer close(out)
		for i := 1; i <= 10; i++ {
			out <- i
		}
	}()

	return out
}

func doubler(in <-chan int) <-chan int {
	out := make(chan int)

	go func() {
		defer close(out)
		for i := range in {
			out <- i * 2
			time.Sleep(500 * time.Millisecond)
		}
	}()

	return out
}

func reader(in <-chan int) {
	for i := range in {
		fmt.Println(i)
	}
}

func main() {
	reader(doubler(writer()))
}
