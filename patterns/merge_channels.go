/**

### Паттерн: Классический Fan-In (Merge Channels)

Объединяет данные из нескольких входных каналов в один общий выходной канал (`out`). Работает до тех пор, пока не иссякнут и не закроются **все** входные каналы.

#### Как это работает
1. **Запуск воркеров.** На каждый входной канал запускается своя горутина. Цикл `for data := range ch` читает значения из канала до его закрытия, после чего автоматически завершается.
2. **Подсчёт активных каналов.** `sync.WaitGroup` отслеживает, сколько горутин ещё продолжают работу. Выход каждой горутины уменьшает счётчик через `defer wg.Done()`.
3. **Асинхронное закрытие `out`.** Отдельная фоновая горутина ждёт обнуления счётчика (`wg.Wait()`) и только после этого закрывает `out`. Это позволяет функции `mergeChannels` сразу вернуть канал читателю, не блокируя основной поток.

#### Ключевые нюансы реализации
* **Направление каналов в сигнатуре (`<-chan int`).** Входные каналы объявлены как доступные только для чтения (`receive-only`). Это защищает функцию от случайной записи в чужой канал или попытки его закрыть на уровне компиляции.
* **Обязательное закрытие всех входных каналов.** Если хотя бы один переданный канал никогда не закроется, его воркер не выйдет из цикла `range`, `wg.Wait()` зависнет навсегда, а цикл `for data := range out` у читателя заблокируется (deadlock или утечка горутин).
* **Оптимизация `wg.Add(len(cs))`.** Счётчик группы выставляется сразу на общее количество каналов до цикла, а не инкрементируется по единице на каждой итерации.
* **Риск утечки при раннем выходе читателя.** В этом базовом варианте нет механизма отмены (`done` или `context.Context`). Если потребитель перестанет читать из `out` раньше времени (например, сделает `break` из цикла `range`), воркеры зависнут на строке `out <- data`.
* **Порядок данных не гарантирован.** Данные попадают в `out` в том порядке, в котором успевают сработать планировщик Go и отправители (в примере может вывестись как `1, 2`, так и `2, 1`).

*/

package main

import (
	"fmt"
	"sync"
)

func mergeChannels(cs ...<-chan int) chan int {
	out := make(chan int)
	wg := sync.WaitGroup{}
	wg.Add(len(cs))

	for _, c := range cs {
		go func(ch <-chan int) {
			defer wg.Done()
			for data := range ch {
				out <- data
			}
		}(c)
	}

	// Горутина для ожидания завершения всех воркеров и закрытия выходного канала
	go func() {
		wg.Wait()
		close(out)
	}()

	return out
}

func main() {
	ch1 := make(chan int)
	ch2 := make(chan int)

	// Запись в небуферизованные каналы в отдельных горутинах
	go func() {
		ch1 <- 1
		close(ch1)
	}()

	go func() {
		ch2 <- 2
		close(ch2)
	}()

	out := mergeChannels(ch1, ch2)

	// Теперь этот цикл корректно завершится, когда канал out закроется
	for data := range out {
		fmt.Println(data)
	}
}
